import { shelfInk, tint } from "@/lib/colors";
import { qrSvg, siteUrl } from "@/lib/qr";

/** Server component: QR code that opens the given site path. */
/** `accent` (shelf colour): tinted card with a coloured edge; the QR itself stays on white for scanning. */
export async function BookQr({ path, label, code, accent }: { path: string; label: string; code: string; accent?: string }) {
  const svg = await qrSvg(path);
  return (
    <div
      className="surface flex items-center gap-4 rounded-xl border-l-4 p-4"
      style={accent ? { background: tint(accent, 0.92), borderLeftColor: shelfInk(accent) } : undefined}
      data-testid="book-qr"
    >
      <div
        className="size-24 shrink-0 rounded-lg bg-white p-1.5 shadow-sm [&_svg]:h-full [&_svg]:w-full"
        role="img"
        aria-label={`QR ${code}`}
        // SVG is generated by the qrcode library from our own URL — not user HTML.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <div className="min-w-0 text-sm">
        <p className="font-medium">{label}</p>
        <p className="mt-1 break-all text-xs text-muted-foreground">{siteUrl(path)}</p>
      </div>
    </div>
  );
}
